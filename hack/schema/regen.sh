#!/usr/bin/env bash
# Scrub a schema-only pg_dump into a publishable baseline file.
#
# Usage:
#   pg_dump --schema-only --no-owner --no-privileges --no-security-labels \
#           --no-tablespaces -d <db> | ./regen.sh main    > 001_main.sql
#   pg_dump ... -d <control-db>      | ./regen.sh control > 002_control.sql
#   ./regen.sh main dump.sql > 001_main.sql        # dump from a file instead
#
# See README.md. Connection details are not handled here; run pg_dump yourself.
set -euo pipefail

kind="${1:?usage: regen.sh main|control [dump.sql]}"
case "$kind" in main|control) ;; *) echo "kind must be main or control" >&2; exit 2 ;; esac
src="${2:--}"

python3 -I - "$kind" "$src" <<'PY'
import re, sys

kind, src = sys.argv[1], sys.argv[2]
text = sys.stdin.read() if src == "-" else open(src, encoding="utf-8").read()

# Roles that RLS policies are attached to. Created below if missing.
APP_ROLE = "falcon_id_app"

# pg_dump object blocks start with "-- Name: <obj>; Type: <type>; ..." after a "--" line.
parts = re.split(r"(?m)^--\n(?=-- Name: )", text)
header, blocks = parts[0], parts[1:]

DROP_NAME = re.compile(r"keystone|user_search", re.I)

out = []
for b in blocks:
    m = re.match(r"-- Name: ([^;]*); Type: ([^;]*);", b)
    name, typ = (m.group(1), m.group(2)) if m else ("", "")
    if DROP_NAME.search(name):
        continue
    if typ in ("EXTENSION", "COMMENT") and "EXTENSION" in name.upper():
        continue
    if typ in ("PUBLICATION", "SUBSCRIPTION", "EVENT TRIGGER", "ACL", "DEFAULT ACL"):
        continue
    # drop comment lines and psql meta-commands (\restrict etc.)
    lines = []
    for ln in b.splitlines():
        if re.match(r"\s*--", ln) or ln.startswith("\\"):
            continue
        if ln.startswith("COMMENT ON"):  # free text carries internal references
            continue
        lines.append(ln)
    body = "\n".join(lines).strip()
    if not body:
        continue
    out.append(body)

sql = "\n\n".join(out) + "\n"

# neutralise internal values
sql = sql.replace("hexxlock_tenant_id", "internal_tenant_id")
sql = sql.replace("Platform-internal tenant", "platform-internal tenant")
sql = re.sub(r"(hr_ldap_server character varying DEFAULT )'[^']*'", r"\1''", sql)
sql = re.sub(r"(hr_ldap_(?:bind_dn|base_dn|group_base_dn) character varying DEFAULT )'[^']*'", r"\1''", sql)

hdr = f"""-- Falcon ID schema baseline ({kind}). Schema only, no data.
-- Generated by hack/schema/regen.sh; do not edit by hand. See README.md.

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET check_function_bodies = false;
SET search_path = public;
"""
if kind == "main":
    hdr += f"""
-- RLS policies target this role; the app connects as it in production.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
        CREATE ROLE {APP_ROLE} NOLOGIN;
    END IF;
END
$$;
"""
sys.stdout.write(hdr + "\n" + sql)
PY
