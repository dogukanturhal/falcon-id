func TestAPIKeyAuth_InternalService_SkipsValidation(t *testing.T) {
	// When is_internal_service=true is already set the middleware must skip all
	// API-key checks and call next immediately.
	repo := &fakeAPIKeyRepo{
		getByPrefixFn: func(_ context.Context, _ string) (*models.APIKey, error) {
			t.Fatal("GetByPrefix must not be called for internal services")
			return nil, nil
		},
	}
	m := newAPIKeyMiddleware(repo)

	var nextCalled bool
	w := httptest.NewRecorder()
	_, router := gin.CreateTestContext(w)
	router.GET("/test",
		// Pre-set the internal service flag (as InternalServiceAuth would do).
		func(c *gin.Context) {
			c.Set("is_internal_service", true)
			c.Next()
		},
		m.APIKeyAuth(),
		func(c *gin.Context) {
			nextCalled = true
			c.Status(http.StatusOK)
		},
	)

	req := httptest.NewRequestWithContext(context.Background(), http.MethodGet, "/test", nil)
	router.ServeHTTP(w, req)

	assert.Equal(t, http.StatusOK, w.Code)
	assert.True(t, nextCalled)
}

