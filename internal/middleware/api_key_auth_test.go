// newAPIKeyMiddleware builds a middleware backed by the supplied fake repo.
func newAPIKeyMiddleware(repo *fakeAPIKeyRepo) *APIKeyAuthMiddleware {
	svc := services.NewAPIKeyService(repo)
	return NewAPIKeyAuthMiddleware(svc)
}

// makeValidKey returns an API key string whose prefix matches the one stored in
// the fake repo entry. Because ValidateAPIKey checks the full HMAC hash we use
// a real key generated by the service and record it in the repo entry.
func makeValidKey(t *testing.T) (keyString string, keyEntry *models.APIKey) {
	t.Helper()

	var storedEntry *models.APIKey

	recordingRepo := &fakeAPIKeyRepo{
		createFn: func(_ context.Context, k *models.APIKey) error {
			storedEntry = k
			return nil
		},
	}
	recordingSvc := services.NewAPIKeyService(recordingRepo)
	resp, err := recordingSvc.Create(
		context.Background(),
		uuid.New(), uuid.New(),
		&models.CreateAPIKeyRequest{Name: "test-key"},
	)
	require.NoError(t, err)
	return resp.Key, storedEntry
}

