// recordingClientRepo is a minimal repo stub that returns a fixed
// OAuthToken from GetOAuthTokenByHash and silently accepts every other
// mutation. It keeps the IP-change test independent of the larger mock
// matrix used elsewhere — the only thing under test is whether
// RefreshTokens publishes a CAEIPChanged signal.
type recordingClientRepo struct {
	noopOAuthClientRepo
	storedToken *models.OAuthToken
}

func (r *recordingClientRepo) GetOAuthTokenByHash(_ context.Context, _ string) (*models.OAuthToken, error) {
	return r.storedToken, nil
}

// recordingPublisher captures CAE publish calls. The subject under test is
// what gets emitted, not how the redis publisher is wired up, so no
// testify mock — bare slice keeps the assertions readable.
type recordingPublisher struct {
	mu       sync.Mutex
	messages [][]byte
}

func (p *recordingPublisher) Publish(_ context.Context, _ string, message []byte) error {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.messages = append(p.messages, message)
	return nil
}

func (p *recordingPublisher) calls() int {
	p.mu.Lock()
	defer p.mu.Unlock()
	return len(p.messages)
}

func (p *recordingPublisher) lastMessage() []byte {
	p.mu.Lock()
	defer p.mu.Unlock()
	if len(p.messages) == 0 {
		return nil
	}
	return p.messages[len(p.messages)-1]
}

// freshRefreshTokenFixture returns a token row that looks like one
// generated by an earlier `authorization_code` exchange — populated
// IPAddress, future ExpiresAt, not revoked, refresh_token grant
// supported by the parent client. Caller mutates the IP it wants.
func freshRefreshTokenFixture(t *testing.T, clientUUID, userUUID, tenantID uuid.UUID, originalIP string) *models.OAuthToken {
	t.Helper()
	ip := originalIP
	return &models.OAuthToken{
		ID:           uuid.New(),
		TenantID:     tenantID,
		ClientID:     clientUUID,
		UserID:       &userUUID,
		TokenType:    "access_token",
		Token:        "stored-access-hash",
		Scopes:       []string{"openid", "profile"},
		RefreshToken: stringPointer("stored-refresh-hash"),
		IPAddress:    &ip,
		IsRevoked:    false,
		ExpiresAt:    time.Now().Add(1 * time.Hour),
		CreatedAt:    time.Now().Add(-5 * time.Minute),
		UpdatedAt:    time.Now().Add(-5 * time.Minute),
	}
}

func stringPointer(s string) *string { return &s }

// TestRefreshTokens_PublishesCAEIPChanged_OnIPMismatch asserts the OpenID
// CAEP §5.3 contract: when the request IP on a refresh-token grant
// differs from the IP captured at original token issuance, a
// CAEIPChanged event is published with both addresses in metadata.
// The refresh itself MUST still proceed — CAEP is signal, not
// enforcement; receivers (Talon IAP) make the policy decision.
func TestRefreshTokens_PublishesCAEIPChanged_OnIPMismatch(t *testing.T) {
	tenantID := uuid.New()
	user := subjectUser()
	user.TenantID = tenantID

	client := authzCodeClient([]string{"openid", "profile"})
	client.TenantID = tenantID

	originalIP := "10.0.0.1"
	newIP := "203.0.113.5"

	storedToken := freshRefreshTokenFixture(t, client.ID, user.ID, tenantID, originalIP)

	repo := &recordingClientRepo{storedToken: storedToken}
	userRepo := &fixedUserRepo{user: user}

	svc := newTestOAuthService(t)
	// Replace repos on the service under test.
	svc.clientRepo = repo
	svc.userRepo = userRepo

	pub := &recordingPublisher{}
	svc.SetCAEService(NewCAEService(pub, zap.NewNop()))

	// Plain refresh-token string — service hashes it before lookup;
	// the recording repo ignores the hash and returns storedToken.
	ctx := WithRequestIP(context.Background(), newIP)
	resp, err := svc.RefreshTokens(ctx, client, "irrelevant-plaintext", "")
	require.NoError(t, err, "refresh must succeed even when IP changed (CAEP is signal, not enforcement)")
	require.NotNil(t, resp)

	require.GreaterOrEqual(t, pub.calls(), 1, "CAEIPChanged must be published on IP mismatch")

	last := string(pub.lastMessage())
	assert.Contains(t, last, `"type":"ip_changed"`,
		"published event must carry the CAEIPChanged type literal")
	assert.Contains(t, last, originalIP, "old IP must be carried in metadata.old_ip")
	assert.Contains(t, last, newIP, "new IP must be carried in metadata.new_ip")
	// The refresh-token fixture has no IdP session, so session_id is omitted.
	assert.False(t, strings.Contains(last, `"session_id"`),
		"session_id must be omitted when the prior token has no IdpSessionID")
}

// TestRefreshTokens_NoEventWhenIPMatches asserts no spurious CAE
// signal is emitted when the client returns from the same IP — the
// hot path for sticky-NAT browser sessions.
func TestRefreshTokens_NoEventWhenIPMatches(t *testing.T) {
	tenantID := uuid.New()
	user := subjectUser()
	user.TenantID = tenantID
	client := authzCodeClient([]string{"openid", "profile"})
	client.TenantID = tenantID

	ip := "10.0.0.1"
	storedToken := freshRefreshTokenFixture(t, client.ID, user.ID, tenantID, ip)
	repo := &recordingClientRepo{storedToken: storedToken}

	svc := newTestOAuthService(t)
	svc.clientRepo = repo
	svc.userRepo = &fixedUserRepo{user: user}

	pub := &recordingPublisher{}
	svc.SetCAEService(NewCAEService(pub, zap.NewNop()))

	ctx := WithRequestIP(context.Background(), ip) // same IP
	_, err := svc.RefreshTokens(ctx, client, "irrelevant-plaintext", "")
	require.NoError(t, err)

	assert.Equal(t, 0, pub.calls(),
		"no CAE event must be published when the IP is unchanged")
}

// TestRefreshTokens_NoEventWhenPriorTokenHasNoIP covers pre-fix rows:
// the refresh succeeds normally, no CAE signal is emitted because we
// have no baseline to compare against.
func TestRefreshTokens_NoEventWhenPriorTokenHasNoIP(t *testing.T) {
	tenantID := uuid.New()
	user := subjectUser()
	user.TenantID = tenantID
	client := authzCodeClient([]string{"openid", "profile"})
	client.TenantID = tenantID

	storedToken := freshRefreshTokenFixture(t, client.ID, user.ID, tenantID, "")
	storedToken.IPAddress = nil // explicit pre-fix shape

	repo := &recordingClientRepo{storedToken: storedToken}

	svc := newTestOAuthService(t)
	svc.clientRepo = repo
	svc.userRepo = &fixedUserRepo{user: user}

	pub := &recordingPublisher{}
	svc.SetCAEService(NewCAEService(pub, zap.NewNop()))

	ctx := WithRequestIP(context.Background(), "203.0.113.5")
	_, err := svc.RefreshTokens(ctx, client, "irrelevant-plaintext", "")
	require.NoError(t, err)

	assert.Equal(t, 0, pub.calls(),
		"no CAE event must be published when prior token has no IP baseline")
}

// fixedUserRepo returns a single user from GetByID regardless of the
// requested ID — sufficient because RefreshTokens only reads user data
// after the token-row lookup that the recordingClientRepo controls.
type fixedUserRepo struct{ user *models.User }

func (r *fixedUserRepo) GetByID(_ context.Context, _ uuid.UUID) (*models.User, error) {
	return r.user, nil
}

func (r *fixedUserRepo) HasAnyMFAFactor(_ context.Context, _ uuid.UUID) (bool, error) {
	if r.user == nil {
		return false, nil
	}
	return r.user.MFAEnabled, nil
}
