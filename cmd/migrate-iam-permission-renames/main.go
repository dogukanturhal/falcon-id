// Command migrate-iam-permission-renames copies iam_role_permissions grants
// from the old (hyphenated) permission rows to their new (underscored)
// counterparts introduced by the ReBAC Phase 1 identifier refactor
// (t-582, hexxlock/business!59, hexxlock/frontend!213).
//
// # Why this exists
//
// iam_permissions.name (module:resource:action) is the natural/unique key
// used by RegisterPermissionsBatch's `ON CONFLICT (name) DO UPDATE`
// (internal/repositories/permission_repository.go). Renaming a resource
// segment — e.g. sd:sales-orders:create -> sd:sales_orders:create — does
// NOT update the existing row in place: the next time the owning .NET
// module calls RegisterModule with its new manifest, the upsert inserts a
// BRAND NEW row with a new id, because the ON CONFLICT target (name) no
// longer matches the old row. Every existing iam_role_permissions grant is
// foreign-keyed to the OLD row's id, so without this tool every role that
// held sd:sales-orders:create would silently lose that permission the
// moment sd:sales_orders:create's manifest deploys, even though nothing
// about the registration path itself is broken.
//
// Cleaning up the old, now-unreferenced permission rows is deliberately
// NOT this tool's job: falcon-id already has a deprecation/replacement
// lifecycle for that (Permission.DeprecatedAt / SunsetAt /
// ReplacementPermission, RegisterModuleRequest.Prune) which soft-deprecates
// unlisted permissions with a 30-day sunset window and only hard-deletes
// once PermissionRepository.DeleteIfNotInUse confirms no
// iam_role_permissions row still references them. That sweep runs
// automatically once the renamed manifests register — this tool only needs
// to make sure grants survive the handoff before the sweep can safely run.
//
// # When to run this
//
// The new (underscored) permission rows do not exist until the renamed
// .NET modules from business!59 have actually deployed and re-registered
// their manifests with falcon-id (RegisterModule runs on service startup).
// Running this tool before that deploy is a harmless no-op: every pair is
// reported "new-not-registered-yet" and skipped. Re-run it after the
// deploy to actually copy grants — it is idempotent and safe to run
// repeatedly (e.g. from a post-deploy CI job, or by hand), because every
// write is guarded by a NOT EXISTS check against the destination.
//
// # Realm database isolation
//
// This tool operates against a single database, via DATABASE_URL — the
// same convention as cmd/migrate-user-realm and cmd/resetpw. Most tenants
// share the control-plane/default database, so a single run against it is
// normally sufficient. However falcon-id also supports per-realm dedicated
// databases (see internal/repositories/realm_database_repository.go,
// "Enterprise Realm Database Isolation" Phase 4A): a realm with its own
// row in realm_databases owns its OWN iam_permissions/iam_role_permissions
// tables, which this tool will NOT reach on a default-database run. Before
// declaring the deploy-window migration complete, check for isolated
// realms with:
//
//	SELECT connection_name, host, port, database_name
//	FROM realm_databases WHERE status = 'active';
//
// and, for any rows returned, re-run this tool once per row with
// DATABASE_URL pointed at that realm's own database (decrypt
// password_encrypted per the standard ops runbook — this tool does not
// do that itself, to avoid needing the encryption key for what is
// otherwise a narrowly-scoped grant copy).
//
// # Usage
//
//	DATABASE_URL=postgres://... go run ./cmd/migrate-iam-permission-renames                    # dry run (default)
//	DATABASE_URL=postgres://... go run ./cmd/migrate-iam-permission-renames --apply             # copy grants
//	DATABASE_URL=postgres://... go run ./cmd/migrate-iam-permission-renames --apply --verify    # copy, then verify
//
// The 383 old->new permission-name pairs are embedded from
// permission_renames.json in this directory. They were generated by
// module-expanding the 365-row resource rename inventory from the business
// repo's t-582 audit (a handful of resources — e.g. approval-callback,
// cost-centers, credit-notes, journal-entries — are shared by more than one
// module, which is why 365 resource-level renames become 383 distinct
// module:resource:action permission names). Regenerate the JSON file if the
// rename inventory ever changes; do not hand-edit it.
package main

import (
	"context"
	"embed"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"sort"
	"text/tabwriter"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/dogukanturhal/falcon-id/pkg/database"
)

//go:embed permission_renames.json
var embeddedFS embed.FS

// renamePair is one old->new permission-name mapping, as embedded from
// permission_renames.json.
type renamePair struct {
	Old string `json:"old"`
	New string `json:"new"`
}

// status values for an outcome. Kept as a closed set of string constants
// (rather than an iota) so the summary table and exit-code logic below can
// both switch on human-readable values.
const (
	statusOK             = "ok"                     // grants copied (or nothing to copy) — apply mode
	statusDryRun         = "dry-run"                // would copy N grants — dry-run mode
	statusOldMissing     = "old-missing"            // old permission row doesn't exist (nothing to migrate)
	statusNewPending     = "new-not-registered-yet" // new row doesn't exist yet — re-run after deploy
	statusVerifyMismatch = "verify-mismatch"
	statusError          = "error"
)

type outcome struct {
	pair         renamePair
	oldID        string
	newID        string
	grantsTotal  int
	grantsCopied int
	status       string
	err          error
}

func main() {
	apply := flag.Bool("apply", false, "Actually copy grants. Without this flag, report what would change and exit 0.")
	verify := flag.Bool("verify", false, "After copying (--apply only), verify every role holding an old permission also holds its new counterpart.")
	flag.Parse()

	databaseURL := os.Getenv("DATABASE_URL")
	if databaseURL == "" {
		fatal("DATABASE_URL environment variable is required")
	}

	pairs, err := loadPairs()
	if err != nil {
		fatal("%v", err)
	}

	db, err := database.NewPostgresDB(databaseURL)
	if err != nil {
		fatal("failed to connect to database: %v", err)
	}
	defer db.Close()

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	fmt.Printf("\n=== migrate-iam-permission-renames ===\n")
	fmt.Printf("  pairs       : %d\n", len(pairs))
	fmt.Printf("  mode        : %s\n", modeLabel(*apply))
	fmt.Printf("  verify      : %v\n\n", *apply && *verify)

	outcomes := make([]outcome, 0, len(pairs))
	for _, p := range pairs {
		outcomes = append(outcomes, processPair(ctx, db, p, *apply))
	}

	if *apply && *verify {
		runVerification(ctx, db, outcomes)
	}

	printSummary(outcomes, *apply)

	if hasFailures(outcomes) {
		os.Exit(1)
	}
}

func modeLabel(apply bool) string {
	if apply {
		return "APPLY (--apply set)"
	}
	return "DRY-RUN (pass --apply to copy grants)"
}

func loadPairs() ([]renamePair, error) {
	b, err := embeddedFS.ReadFile("permission_renames.json")
	if err != nil {
		return nil, fmt.Errorf("read embedded permission_renames.json: %w", err)
	}
	var pairs []renamePair
	if err := json.Unmarshal(b, &pairs); err != nil {
		return nil, fmt.Errorf("parse permission_renames.json: %w", err)
	}
	if len(pairs) == 0 {
		return nil, errors.New("permission_renames.json is empty")
	}
	return pairs, nil
}

// processPair looks up the old and new permission rows by name and, in
// --apply mode, copies any iam_role_permissions grants from the old id to
// the new id. The copy is a single idempotent INSERT ... SELECT guarded by
// NOT EXISTS, so re-running this tool never creates duplicate grants.
func processPair(ctx context.Context, db *database.PostgresDB, p renamePair, apply bool) outcome {
	out := outcome{pair: p}

	var oldID string
	err := db.Pool.QueryRow(ctx, `SELECT id FROM iam_permissions WHERE name = $1`, p.Old).Scan(&oldID)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		out.status = statusOldMissing
		return out
	case err != nil:
		out.status = statusError
		out.err = fmt.Errorf("lookup old %q: %w", p.Old, err)
		return out
	}
	out.oldID = oldID

	var newID string
	err = db.Pool.QueryRow(ctx, `SELECT id FROM iam_permissions WHERE name = $1`, p.New).Scan(&newID)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		out.status = statusNewPending
		return out
	case err != nil:
		out.status = statusError
		out.err = fmt.Errorf("lookup new %q: %w", p.New, err)
		return out
	}
	out.newID = newID

	if oldID == newID {
		// Can't happen (name is UNIQUE, and Old != New for every embedded
		// pair) but guard rather than assume.
		out.status = statusOK
		return out
	}

	if err := db.Pool.QueryRow(ctx,
		`SELECT count(*) FROM iam_role_permissions WHERE permission_id = $1`, oldID,
	).Scan(&out.grantsTotal); err != nil {
		out.status = statusError
		out.err = fmt.Errorf("count grants for %q: %w", p.Old, err)
		return out
	}

	if !apply {
		out.status = statusDryRun
		return out
	}

	tag, err := db.Pool.Exec(ctx, `
		INSERT INTO iam_role_permissions (role_id, permission_id, created_by)
		SELECT old.role_id, $2::uuid, old.created_by
		FROM iam_role_permissions old
		WHERE old.permission_id = $1::uuid
		  AND NOT EXISTS (
		      SELECT 1 FROM iam_role_permissions existing
		      WHERE existing.role_id = old.role_id
		        AND existing.permission_id = $2::uuid
		  )
	`, oldID, newID)
	if err != nil {
		out.status = statusError
		out.err = fmt.Errorf("copy grants %q -> %q: %w", p.Old, p.New, err)
		return out
	}
	out.grantsCopied = int(tag.RowsAffected())
	out.status = statusOK
	return out
}

// runVerification re-checks, after an --apply run, that no role which held
// an old permission is missing the corresponding new one. It mutates the
// outcome in place to statusVerifyMismatch on failure.
func runVerification(ctx context.Context, db *database.PostgresDB, outcomes []outcome) {
	for i := range outcomes {
		o := &outcomes[i]
		if o.status != statusOK || o.oldID == "" || o.newID == "" {
			continue
		}
		var missing int
		err := db.Pool.QueryRow(ctx, `
			SELECT count(*) FROM iam_role_permissions o
			WHERE o.permission_id = $1::uuid
			  AND NOT EXISTS (
			      SELECT 1 FROM iam_role_permissions n
			      WHERE n.role_id = o.role_id AND n.permission_id = $2::uuid
			  )
		`, o.oldID, o.newID).Scan(&missing)
		if err != nil {
			o.status = statusError
			o.err = fmt.Errorf("verify %q -> %q: %w", o.pair.Old, o.pair.New, err)
			continue
		}
		if missing > 0 {
			o.status = statusVerifyMismatch
			o.err = fmt.Errorf("%d role(s) still hold %q without holding %q", missing, o.pair.Old, o.pair.New)
		}
	}
}

func printSummary(outcomes []outcome, apply bool) {
	counts := map[string]int{}
	totalGrants := 0
	for _, o := range outcomes {
		counts[o.status]++
		if apply {
			totalGrants += o.grantsCopied
		} else {
			totalGrants += o.grantsTotal
		}
	}

	fmt.Println("--- by status ---")
	statuses := make([]string, 0, len(counts))
	for s := range counts {
		statuses = append(statuses, s)
	}
	sort.Strings(statuses)
	for _, s := range statuses {
		fmt.Printf("  %-24s %d\n", s, counts[s])
	}
	if apply {
		fmt.Printf("\n  grants copied total   : %d\n", totalGrants)
	} else {
		fmt.Printf("\n  grants that WOULD copy: %d (re-run with --apply)\n", totalGrants)
	}

	// Detail table for anything that needs operator attention.
	interesting := make([]outcome, 0)
	for _, o := range outcomes {
		if o.status == statusError || o.status == statusVerifyMismatch {
			interesting = append(interesting, o)
		}
	}
	if len(interesting) > 0 {
		fmt.Println("\n--- needs attention ---")
		w := tabwriter.NewWriter(os.Stdout, 0, 2, 2, ' ', 0)
		_, _ = fmt.Fprintln(w, "OLD\tNEW\tSTATUS\tDETAIL")
		for _, o := range interesting {
			detail := ""
			if o.err != nil {
				detail = o.err.Error()
			}
			_, _ = fmt.Fprintf(w, "%s\t%s\t%s\t%s\n", o.pair.Old, o.pair.New, o.status, detail)
		}
		_ = w.Flush()
	}

	pending := counts[statusNewPending]
	if pending > 0 {
		fmt.Printf("\nNOTE: %d pair(s) have no new-permission row yet — this is expected before the\n", pending)
		fmt.Println("      owning .NET module has deployed and re-registered its manifest. Re-run")
		fmt.Println("      this tool (with --apply) after that deploy completes.")
	}
	fmt.Println()
}

func hasFailures(outcomes []outcome) bool {
	for _, o := range outcomes {
		if o.status == statusError || o.status == statusVerifyMismatch {
			return true
		}
	}
	return false
}

func fatal(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "migrate-iam-permission-renames: "+format+"\n", args...)
	os.Exit(2)
}
